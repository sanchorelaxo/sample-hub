"""Milestone 2 — conversion matrix, device-free.

Every §6 row of SPEC.md as a pure function of (canonical bytes, params).
No device I/O. Each test feeds ffmpeg-generated bytes and decodes the result
with ``struct`` — no mocks. These will be RED until server/convert.py exists.
"""
from __future__ import annotations

import array
import struct
import subprocess
from pathlib import Path

# ---- test helpers: decode real bytes, never mocks ----------------------

FFMPEG = "ffmpeg"


def run_ffmpeg(args: list[str], stdin: bytes | None = None) -> bytes:
    proc = subprocess.run(
        [FFMPEG, "-nostdin", "-v", "error", *args],
        input=stdin,
        capture_output=True,
        timeout=60,
    )
    if proc.returncode != 0:
        raise AssertionError(proc.stderr.decode("utf-8", "replace"))
    return proc.stdout


def canonical_wav(seconds: float = 1.0, freq: float = 440.0) -> bytes:
    """A 48 kHz stereo float32 WAV — the hub's canonical form."""
    return run_ffmpeg(
        [
            "-f", "lavfi",
            "-i", f"sine=frequency={freq}:duration={seconds}",
            "-ar", "48000", "-ac", "2",
            "-c:a", "pcm_f32le", "-f", "wav", "-",
        ]
    )


def canonical_with_silence(tone_s: float = 0.5, freq: float = 440.0) -> bytes:
    """0.5s silence + tone + 0.5s silence, canonical form."""
    return run_ffmpeg(
        [
            "-f", "lavfi", "-i", "aevalsrc=0:s=48000:d=0.5",
            "-f", "lavfi", "-i", f"sine=frequency={freq}:duration={tone_s}",
            "-f", "lavfi", "-i", "aevalsrc=0:s=48000:d=0.5",
            "-filter_complex", "[0:a][1:a][2:a]concat=n=3:v=0:a=1[out]",
            "-map", "[out]",
            "-ar", "48000", "-ac", "2",
            "-c:a", "pcm_f32le", "-f", "wav", "-",
        ]
    )


def wav_fmt(data: bytes) -> tuple[int, int, int, int]:
    """Return (format_tag, channels, rate, bits) from a WAV fmt chunk."""
    assert data[:4] == b"RIFF" and data[8:12] == b"WAVE", "not a WAV"
    off = 12
    while off + 8 <= len(data):
        cid = data[off : off + 4]
        size = struct.unpack("<I", data[off + 4 : off + 8])[0]
        if cid == b"fmt ":
            tag, channels, rate = struct.unpack("<HHI", data[off + 8 : off + 16])
            bits = struct.unpack("<H", data[off + 8 + 14 : off + 8 + 16])[0]
            return tag, channels, rate, bits
        off += 8 + size + (size & 1)
    raise AssertionError("no fmt chunk")


def wav_duration_s(data: bytes) -> float:
    """Duration from the data chunk size, not a header claim."""
    tag, channels, rate, bits = wav_fmt(data)
    off = 12
    while off + 8 <= len(data):
        cid = data[off : off + 4]
        size = struct.unpack("<I", data[off + 4 : off + 8])[0]
        if cid == b"data":
            return (size / (channels * (bits // 8))) / rate
        off += 8 + size + (size & 1)
    raise AssertionError("no data chunk")


def float_samples_mono(data: bytes) -> tuple[array.array, int]:
    """Decode a WAV's first channel to float32 (downmix if stereo)."""
    tag, channels, rate, bits = wav_fmt(data)
    assert tag == 0x0003 and bits == 32, f"not float32 WAV: tag={tag} bits={bits}"
    off = 12
    pcm = b""
    while off + 8 <= len(data):
        cid = data[off : off + 4]
        size = struct.unpack("<I", data[off + 4 : off + 8])[0]
        if cid == b"data":
            pcm = data[off + 8 : off + 8 + size]
            break
        off += 8 + size + (size & 1)
    samples = array.array("f")
    samples.frombytes(pcm[: len(pcm) - (len(pcm) % 4)])
    if channels == 1:
        return samples, rate
    out = array.array("f")
    for i in range(0, len(samples) - 1, 2):
        out.append((samples[i] + samples[i + 1]) / 2.0)
    return out, rate


def aiff_comm(data: bytes) -> tuple[int, int, int, str]:
    """Return (channels, rate, bits, compression) from a FORM/AIFF COMM."""
    assert data[:4] == b"FORM" and data[8:12] in (b"AIFF", b"AIFC"), "not AIFF"
    off = 12
    while off + 8 <= len(data):
        cid = data[off : off + 4]
        size = struct.unpack(">I", data[off + 4 : off + 8])[0]
        if cid == b"COMM":
            raw = data[off + 8 : off + 8 + min(size, 22)]
            channels, frames, bits = struct.unpack(">hIh", raw[0:8])
            # 10-byte 80-bit extended rate, then 4-byte compression id
            rate = _extended(raw[8:18])
            comp = raw[18:22].decode("latin-1") if len(raw) >= 22 else "NONE"
            return channels, int(round(rate)), bits, comp
        off += 8 + size + (size & 1)
    raise AssertionError("no COMM chunk")


def _extended(raw: bytes) -> float:
    exp = struct.unpack(">H", raw[0:2])[0]
    mant = struct.unpack(">Q", raw[2:10])[0]
    return mant * 2.0 ** (exp - 16383 - 63)


def zero_crossing_freq(samples: array.array, rate: int) -> float:
    """Dominant frequency of a (clean) signal via zero crossings."""
    crossings = 0
    for i in range(1, len(samples)):
        if (samples[i - 1] < 0) != (samples[i] < 0):
            crossings += 1
    seconds = len(samples) / rate
    return crossings / 2 / seconds if seconds else 0.0


