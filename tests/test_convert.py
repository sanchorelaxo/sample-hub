# ---- audio rows --------------------------------------------------------

def test_spotykach_passthrough_is_canonical():
    src = canonical_wav()
    out = to_spotykach(src)
    tag, channels, rate, bits = wav_fmt(out)
    assert (tag, channels, rate, bits) == (0x0003, 2, 48000, 32)


def test_sp404_is_16bit_48khz():
    out = to_sp404(canonical_wav())
    tag, channels, rate, bits = wav_fmt(out)
    assert tag == 0x0001          # linear PCM, not float
    assert bits == 16
    assert rate == 48000          # SP-404 native rate (SparkyMK2)
    assert channels == 2


def test_op1_drum_is_aifc_mono_44100_sowt():
    out = to_op1_drum(canonical_wav(seconds=2.0), filename="kick.wav")
    channels, rate, bits, comp = aiff_comm(out)
    assert channels == 1
    assert rate == 44100
    assert bits == 16
    assert comp == "sowt"


def test_op1_drum_rejects_over_12_seconds():
    try:
        to_op1_drum(canonical_wav(seconds=13.0), filename="too-long.wav")
    except ValueError:
        return
    raise AssertionError("a 13 s sample should be refused, not truncated")


def test_wave_bard_downmixes_to_mono():
    out = to_wave_bard(canonical_wav())
    tag, channels, rate, bits = wav_fmt(out)
    assert channels == 1
    assert rate == 48000


def test_wave_bard_trims_silence():
    out = to_wave_bard(canonical_with_silence(tone_s=0.5))
    duration = wav_duration_s(out)
    # 0.5 s of tone inside 1.5 s of total; trim must drop the dead ends
    assert 0.3 < duration < 0.8, f"trimmed duration {duration:.2f}s out of range"


def test_wave_bard_tunes_440_to_nearest_c():
    out = to_wave_bard(canonical_wav(freq=440.0))
    samples, rate = float_samples_mono(out)
    got = zero_crossing_freq(samples, rate)
    # nearest C to A4=440 is C5=523.25 Hz
    assert 505.0 < got < 542.0, f"tuned to {got:.1f} Hz, expected ~523.25"


# ---- rhythm rows -------------------------------------------------------

def _rhythm():
    return {
        "steps": 16,
        "gates": [1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0, 0],
        "cv": [0.8] * 16,
    }


def test_wave_bard_rhythm_maps_steps_and_pattern():
    r = wave_bard_rhythm(_rhythm())
    assert r["steps"] == 16
    assert r["pattern"] == [0, 4, 8, 12]
    assert r["type"] == "rhythm"


def test_fx_wizard_rhythm_maps_step_count():
    r = fx_wizard_rhythm(_rhythm())
    assert r["step_count"] == 16
    assert r["pattern"] == [0, 4, 8, 12]
